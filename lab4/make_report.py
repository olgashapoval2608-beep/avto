def p(text, center=False, bold=False, indent=True, italic=False):
    par = d.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent and not center:
        par.paragraph_format.first_line_indent = Cm(1.25)
    r = par.add_run(text); r.bold = bold; r.italic = italic
    return par

def lead(head, text):
    par = p("")
    par.add_run(head).bold = True
    par.add_run(" " + text)

def code(text):
    for line in text.strip("\n").split("\n"):
        par = d.add_paragraph()
        par.paragraph_format.left_indent = Cm(1.25)
        par.paragraph_format.line_spacing = 1.0
        r = par.add_run(line); r.font.name = "Courier New"; r.font.size = Pt(11)
        r._element.rPr.rFonts.set(qn("w:eastAsia"), "Courier New")

n = [0]
def fig(img, caption, width=16):
    n[0] += 1
    par = d.add_paragraph(); par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_before = Pt(6)
    par.add_run().add_picture(str(ROOT / "img" / img), width=Cm(width))
    c = p(f"Рисунок {n[0]} – {caption}", center=True)
    c.paragraph_format.space_after = Pt(8)
    return n[0]

def table(rows, caption, widths):
    p(caption, indent=True)
    t = d.add_table(rows=0, cols=len(rows[0])); t.style = "Table Grid"
    for i, row in enumerate(rows):
        cells = t.add_row().cells
        for j, v in enumerate(row):
            cells[j].width = Cm(widths[j])
            cp = cells[j].paragraphs[0]; cp.paragraph_format.line_spacing = 1.0
            run = cp.add_run(v); run.font.size = Pt(12); run.bold = (i == 0)
    d.add_paragraph()

